#!/usr/bin/env node
// Compiles the named building footprints into the code, so nothing has to read them
// from Firestore. Runs before every functions and website build (see their package.json).
//
//   node scripts/generate-buildings.mjs [path/to/buildings.geojson]
//
// Defaults to geofence/buildings.geojson (name footprints with geofence/labeler.html).
// Writes:
//   functions/src/generated/buildings.ts  the footprints and names (for geofencing)
//   website/app/generated/buildings.ts    just the names (for the admin dropdown)

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(process.argv[2] ?? join(root, "geofence", "buildings.geojson"));

const geojson = JSON.parse(readFileSync(source, "utf8"));
if (geojson?.type !== "FeatureCollection" || !Array.isArray(geojson.features)) {
  throw new Error(`${source} isn't a GeoJSON FeatureCollection`);
}

// footprints nobody has named yet aren't geofenced
const buildings = geojson.features
  .filter((f) =>
    typeof f?.properties?.name === "string" && f.properties.name.trim() !== "" &&
    (f.geometry?.type === "Polygon" || f.geometry?.type === "MultiPolygon"))
  .map((f) => ({
    type: "Feature",
    properties: { name: f.properties.name.trim() },
    geometry: f.geometry,
  }));

const names = buildings.map((b) => b.properties.name);
const duplicates = names.filter((name, i) => names.indexOf(name) !== i);
if (duplicates.length > 0) {
  throw new Error(`Building names must be unique. Repeated: ${[...new Set(duplicates)].join(", ")}`);
}

const header = `// GENERATED by scripts/generate-buildings.mjs from ${source.startsWith(root) ? source.slice(root.length + 1) : source}.
// Don't edit by hand: change the GeoJSON and rebuild.
`;

function write(path, body) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, header + body);
}

write(
  join(root, "functions", "src", "generated", "buildings.ts"),
  `import type { Feature, MultiPolygon, Polygon } from "geojson";

export const BUILDING_NAMES: readonly string[] = ${JSON.stringify(names)};

// GeoJSON coordinates are (longitude, latitude)
export const BUILDINGS: Feature<Polygon | MultiPolygon, { name: string }>[] = ${JSON.stringify(buildings)};
`,
);

write(
  join(root, "website", "app", "generated", "buildings.ts"),
  `export const BUILDING_NAMES: readonly string[] = ${JSON.stringify(names)};
`,
);

console.log(`Generated ${names.length} buildings: ${names.join(", ")}`);
